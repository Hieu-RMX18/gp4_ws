SUPPORTED_GLYPHS = frozenset(GLYPHS.keys())


def generate_text_strokes(
    text: str, height_m: float, char_spacing_m: float
) -> List[StrokeSegment]:
    """Convert text into scaled 2D draw/travel stroke segments."""
    if not isinstance(text, str) or not text:
        raise ValueError("text must be a non-empty string.")
    if height_m <= 0.0:
        raise ValueError("height_m must be > 0.")
    if char_spacing_m < 0.0:
        raise ValueError("char_spacing_m must be >= 0.")

    segments: List[StrokeSegment] = []
    cursor_x = 0.0
    previous_end: Point2D | None = None

    for character in text:
        glyph = GLYPHS.get(character)
        if glyph is None:
            raise ValueError(f"Unsupported glyph: {character!r}")

        for stroke in glyph.strokes:
            scaled_points = tuple(
                (cursor_x + (point_x * height_m), point_y * height_m)
                for point_x, point_y in stroke
            )
            if previous_end is not None:
                segments.append(
                    StrokeSegment(
                        kind="travel",
                        points_2d=(previous_end, scaled_points[0]),
                        closed=False,
                    )
                )
            segments.append(
                StrokeSegment(
                    kind="draw",
                    points_2d=scaled_points,
                    closed=scaled_points[0] == scaled_points[-1],
                )
            )
            previous_end = scaled_points[-1]

        cursor_x += (glyph.advance_width * height_m) + char_spacing_m

    return segments


