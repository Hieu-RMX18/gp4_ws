"""Simple single-stroke vector font for SIM-only draw_text macros."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Tuple


Point2D = Tuple[float, float]


@dataclass(frozen=True)
class Glyph:
    advance_width: float
    strokes: Tuple[Tuple[Point2D, ...], ...]


@dataclass(frozen=True)
class StrokeSegment:
    kind: str
    points_2d: Tuple[Point2D, ...]
    closed: bool


def _glyph(advance_width: float, *strokes: Tuple[Point2D, ...]) -> Glyph:
    return Glyph(
        advance_width=advance_width, strokes=tuple(tuple(stroke) for stroke in strokes)
    )


